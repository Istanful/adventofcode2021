const isIntersecting = require("./isIntersecting");

describe("isIntersecting", () => {
  [
    [
      [
        [0, 1],
        [2, 1],
      ],
      [
        [1, 0],
        [1, 2],
      ],
      true,
    ],
    [
      [
        [0, 0],
        [2, 0],
      ],
      [
        [3, 0],
        [4, 0],
      ],
      false,
    ],
    [
      [
        [0, 0],
        [2, 0],
      ],
      [
        [0, 1],
        [2, 1],
      ],
      false,
    ],
    [
      [
        [1, 0],
        [1, 2],
      ],
      [
        [0, 1],
        [2, 1],
      ],
      true,
    ],
    [
      [
        [0, 0],
        [1, 0],
      ],
      [
        [1, 0],
        [2, 0],
      ],
      true,
    ],
    [
      [
        [0, 0],
        [2, 2],
      ],
      [
        [2, 0],
        [0, 2],
      ],
      true,
    ],
    [
      [
        [0, 0],
        [2, 2],
      ],
      [
        [1, 0],
        [3, 2],
      ],
      false,
    ],
    [
      [
        [2, 2],
        [2, 1],
      ],
      [
        [6, 4],
        [2, 0],
      ],
      false,
    ],
    [
      [
        [2, -1],
        [2, -2],
      ],
      [
        [6, 4],
        [2, 0],
      ],
      false,
    ],
    [
      [
        [2, 2],
        [2, -1],
      ],
      [
        [6, 4],
        [3, 1],
      ],
      false,
    ],
    [
      [
        [2, 2],
        [2, -1],
      ],
      [
        [0, -2],
        [1, -1],
      ],
      false,
    ],
    [
      [
        [6, 4],
        [2, 0],
      ],
      [
        [2, 2],
        [2, 1],
      ],
      false,
    ],
    [
      [
        [6, 4],
        [2, 0],
      ],
      [
        [2, -1],
        [2, -2],
      ],
      false,
    ],
    [
      [
        [6, 4],
        [3, 1],
      ],
      [
        [2, 2],
        [2, -1],
      ],
      false,
    ],
    [
      [
        [0, -2],
        [1, -1],
      ],
      [
        [2, 2],
        [2, -1],
      ],
      false,
    ],
    [
      [
        [2, 2],
        [2, 1],
      ],
      [
        [-2, 2],
        [-1, 2],
      ],
      false,
    ],
    [
      [
        [-2, 2],
        [-1, 2],
      ],
      [
        [2, 2],
        [2, 1],
      ],
      false,
    ],
    [
      [
        [0, 0],
        [1, 0],
      ],
      [
        [2, 0],
        [3, 0],
      ],
      false,
    ],
    [
      [
        [2, 0],
        [3, 0],
      ],
      [
        [0, 0],
        [1, 0],
      ],
      false,
    ],
    [
      [
        [2, 0],
        [2, 1],
      ],
      [
        [3, 0],
        [3, 1],
      ],
      false,
    ],
  ].forEach(([lineA, lineB, intersecting]) => {
    describe(`when given ${lineA} vs ${lineB}`, () => {
      it(`returns ${intersecting}`, () => {
        expect(isIntersecting(lineA, lineB)).toEqual(intersecting);
      });
    });
  });
});
